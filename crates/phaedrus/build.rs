//! Builds the Monaco script editor (`crates/phaedrus_script_editor`) for
//! wasm32, runs wasm-bindgen on it and embeds the result, so the app needs
//! no web assets at runtime.
//!
//! Needs the wasm32 target (`rustup target add wasm32-unknown-unknown`). If
//! the build fails, the app is still built and falls back to its built-in
//! egui editor; the reason is printed as a cargo warning.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

const CRATE: &str = "phaedrus_script_editor";
const WASM_TARGET: &str = "wasm32-unknown-unknown";
const PROFILE: &str = "script-editor";

fn main() {
    let manifest_dir = PathBuf::from(env("CARGO_MANIFEST_DIR"));
    let root = manifest_dir.join("../..").canonicalize().expect("workspace root");
    let out_dir = PathBuf::from(env("OUT_DIR"));
    println!("cargo::rerun-if-changed={}", root.join("crates").join(CRATE).display());
    println!("cargo::rerun-if-changed={}", root.join("Cargo.lock").display());
    println!("cargo::rerun-if-env-changed=PHAEDRUS_SKIP_SCRIPT_EDITOR");

    let bundle_dir = out_dir.join("script-editor");
    let result = if std::env::var_os("PHAEDRUS_SKIP_SCRIPT_EDITOR").is_some() {
        Err("PHAEDRUS_SKIP_SCRIPT_EDITOR is set".to_owned())
    } else {
        build(&root, &bundle_dir)
    };
    let mut code = String::from("// Generated by build.rs.\n");
    match result {
        Ok(files) => {
            code.push_str("pub const BUILD_ERROR: Option<&str> = None;\n");
            code.push_str("pub static FILES: &[(&str, &[u8])] = &[\n");
            for (name, path) in files {
                writeln!(code, "    ({name:?}, include_bytes!({:?})),", path.display().to_string()).unwrap();
            }
            code.push_str("];\n");
        }
        Err(e) => {
            println!("cargo::warning=script editor not built, the app will use its fallback editor: {e}");
            writeln!(code, "pub const BUILD_ERROR: Option<&str> = Some({e:?});").unwrap();
            code.push_str("pub static FILES: &[(&str, &[u8])] = &[];\n");
        }
    }
    std::fs::write(out_dir.join("script_editor_bundle.rs"), code).expect("write bundle index");
}

fn env(key: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| panic!("{key} is not set"))
}

/// Returns the bundle's files as (served path, path on disk).
fn build(root: &Path, bundle_dir: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    // A separate target dir: the outer build holds the lock on its own.
    let target_dir = std::env::var_os("CARGO_TARGET_DIR").map(PathBuf::from).unwrap_or_else(|| root.join("target"));
    let target_dir = target_dir.join("script-editor");
    let manifest = root.join("Cargo.toml");

    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["build", "-p", CRATE, "--target", WASM_TARGET, "--profile", PROFILE])
        .arg("--manifest-path")
        .arg(&manifest)
        .arg("--target-dir")
        .arg(&target_dir);
    // Settings meant for the outer (native) build must not leak into this one.
    for var in [
        "CARGO_ENCODED_RUSTFLAGS",
        "RUSTFLAGS",
        "CARGO_BUILD_RUSTFLAGS",
        "CARGO_TARGET_DIR",
        "CARGO_BUILD_TARGET",
        "RUSTC_WORKSPACE_WRAPPER",
        "CARGO_MAKEFLAGS",
        "MAKEFLAGS",
        "MFLAGS",
    ] {
        cmd.env_remove(var);
    }
    let output = cmd.output().map_err(|e| format!("could not run cargo: {e}"))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        if stderr.contains("may not be installed") || stderr.contains("can't find crate for `core`") {
            return Err(format!("the {WASM_TARGET} target is missing; run `rustup target add {WASM_TARGET}`"));
        }
        let tail: Vec<&str> = stderr.lines().filter(|l| !l.trim_start().starts_with("Compiling")).collect();
        let tail = tail[tail.len().saturating_sub(15)..].join("\n");
        return Err(format!("cargo build for {WASM_TARGET} failed:\n{tail}"));
    }
    let wasm = target_dir.join(WASM_TARGET).join(PROFILE).join(format!("{CRATE}.wasm"));

    if bundle_dir.exists() {
        std::fs::remove_dir_all(bundle_dir).map_err(|e| e.to_string())?;
    }
    wasm_bindgen_cli_support::Bindgen::new()
        .input_path(&wasm)
        .web(true)
        .map_err(|e| e.to_string())?
        .typescript(false)
        .generate(bundle_dir)
        .map_err(|e| format!("wasm-bindgen failed: {e:#}"))?;

    // Monaco's editor web worker ships inside the monaco crate.
    let worker = monaco_dir(root, &target_dir)?.join("js").join("release").join("editor.worker.js");
    if !worker.is_file() {
        return Err(format!("{} not found", worker.display()));
    }
    std::fs::copy(&worker, bundle_dir.join("editor.worker.js")).map_err(|e| e.to_string())?;

    let mut files = Vec::new();
    collect(bundle_dir, bundle_dir, &mut files).map_err(|e| e.to_string())?;
    files.sort();
    Ok(files)
}

/// The monaco crate's source directory, from `cargo metadata`.
fn monaco_dir(root: &Path, target_dir: &Path) -> Result<PathBuf, String> {
    let output = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args(["metadata", "--format-version", "1", "--filter-platform", WASM_TARGET])
        .arg("--manifest-path")
        .arg(root.join("Cargo.toml"))
        .env("CARGO_TARGET_DIR", target_dir)
        .output()
        .map_err(|e| format!("could not run cargo metadata: {e}"))?;
    if !output.status.success() {
        return Err(format!("cargo metadata failed: {}", String::from_utf8_lossy(&output.stderr)));
    }
    let meta: serde_json::Value = serde_json::from_slice(&output.stdout).map_err(|e| e.to_string())?;
    meta["packages"]
        .as_array()
        .into_iter()
        .flatten()
        .find(|p| p["name"] == "monaco")
        .and_then(|p| p["manifest_path"].as_str())
        .and_then(|m| Path::new(m).parent().map(Path::to_path_buf))
        .ok_or_else(|| "monaco crate not found in cargo metadata".to_owned())
}

fn collect(base: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(base, &path, out)?;
        } else {
            let rel = path.strip_prefix(base).unwrap().to_string_lossy().replace('\\', "/");
            out.push((rel, path));
        }
    }
    Ok(())
}
